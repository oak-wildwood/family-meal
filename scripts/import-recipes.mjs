#!/usr/bin/env node
// Loads the recipe files in public/recipes/*.json into the LOCAL Supabase database.
//
//   node scripts/import-recipes.mjs           write supabase/seed.sql from the recipe files
//   node scripts/import-recipes.mjs --check   exit 1 if supabase/seed.sql is out of date
//   node scripts/import-recipes.mjs --images  upload recipe photos to the local storage bucket
//
// `supabase db reset` runs supabase/seed.sql after the migrations, so a reset rebuilds the
// schema and loads every recipe. The seed is generated, not hand-edited, for the same
// reason public/recipes/index.json is: a copy that can drift will.
//
// Each ingredient line gets a standard ingredient name from supabase/ingredient-names.json,
// keyed by the line's `item` text. A line with no entry stops the import, so a new recipe
// can't land with an ingredient the pantry and shopping list can't match.
//
// `leftover_meals` is left at the column default (0, no leftovers) for every recipe.
// Review it per recipe.
//
// The seed is for the local stack only: it creates a stand-in owner account and owns every
// row with it. Nothing here talks to a hosted project, and --images refuses any URL that
// is not localhost.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { basename, extname } from 'node:path';

const RECIPES_DIR = 'public/recipes';
const NAMES_FILE = 'supabase/ingredient-names.json';
const SEED_FILE = 'supabase/seed.sql';
const BUCKET = 'recipe-photos';
// A made-up local account. No password, so nobody can sign in as it.
const LOCAL_OWNER_ID = '5b0c1f6e-3d7a-4c52-9e1b-0a6d2f8c4e17';
const LOCAL_OWNER_EMAIL = 'owner@example.test';

function loadRecipes() {
  return readdirSync(RECIPES_DIR)
    .filter((name) => name.endsWith('.json') && name !== 'index.json')
    .sort()
    .map((name) => JSON.parse(readFileSync(`${RECIPES_DIR}/${name}`, 'utf8')));
}

const text = (value) => (value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`);
const number = (value) => (value == null ? 'null' : String(Number(value)));
const textArray = (values) =>
  values?.length ? `array[${values.map(text).join(', ')}]::text[]` : `'{}'::text[]`;
const imageObjectPath = (recipe) => (recipe.image ? basename(recipe.image) : null);

/** Builds the full seed script. Throws when an ingredient line has no standard name. */
function buildSeedSql(recipes, { names, staples }) {
  const missing = [];
  const standardName = (item) => {
    const name = names[item];
    if (!name) missing.push(item);
    return name;
  };

  const lines = recipes.flatMap((r) =>
    r.ingredients.map((ing, index) => ({
      slug: r.slug,
      position: index + 1,
      ing,
      name: standardName(ing.item),
    })),
  );
  if (missing.length) {
    throw new Error(
      `No standard ingredient name in ${NAMES_FILE} for:\n  ${[...new Set(missing)].join('\n  ')}`,
    );
  }

  const ingredientNames = [...new Set(lines.map((l) => l.name))].sort();
  const stapleSet = new Set(staples);

  const sql = [];
  sql.push(
    '-- Generated by scripts/import-recipes.mjs from public/recipes/*.json. Do not edit by hand;',
    '-- run `npm run recipes:seed` after changing a recipe or supabase/ingredient-names.json.',
    '-- Runs on `supabase db reset` (local stack only).',
    '',
    '-- A stand-in owner for the local stack: invented email, no password, cannot sign in.',
    'insert into auth.users (',
    '  instance_id, id, aud, role, email, email_confirmed_at,',
    '  confirmation_token, recovery_token, email_change_token_new, email_change,',
    '  raw_app_meta_data, raw_user_meta_data, created_at, updated_at',
    ') values (',
    `  '00000000-0000-0000-0000-000000000000', ${text(LOCAL_OWNER_ID)}, 'authenticated', 'authenticated',`,
    `  ${text(LOCAL_OWNER_EMAIL)}, now(), '', '', '', '',`,
    `  '{"provider": "email", "providers": ["email"]}', '{}', now(), now()`,
    ')',
    'on conflict (id) do nothing;',
    '',
    'insert into public.ingredients (owner_id, name, is_staple) values',
    ingredientNames
      .map((n) => `  (${text(LOCAL_OWNER_ID)}, ${text(n)}, ${stapleSet.has(n)})`)
      .join(',\n') + ';',
    '',
    'insert into public.recipes (',
    '  owner_id, slug, name, description, servings, prep_minutes, cook_minutes, total_minutes,',
    '  category, tags, image_path, based_on, notes',
    ') values',
    recipes
      .map(
        (r) =>
          `  (${text(LOCAL_OWNER_ID)}, ${text(r.slug)}, ${text(r.name)}, ${text(r.description)}, ` +
          `${number(r.servings)}, ${number(r.prepMinutes)}, ${number(r.cookMinutes)}, ${number(r.totalMinutes)},\n` +
          `   ${text(r.category)}, ${textArray(r.tags)}, ${text(imageObjectPath(r))}, ${text(r.basedOn)}, ${textArray(r.notes)})`,
      )
      .join(',\n') + ';',
    '',
    'insert into public.recipe_ingredients (recipe_id, position, qty, unit, item, group_name, ingredient_id)',
    'select r.id, v.position, v.qty::numeric, v.unit::text, v.item, v.group_name::text, i.id',
    'from (values',
    lines
      .map(
        (l) =>
          `  (${text(l.slug)}, ${l.position}, ${number(l.ing.qty)}, ${text(l.ing.unit)}, ` +
          `${text(l.ing.item)}, ${text(l.ing.group)}, ${text(l.name)})`,
      )
      .join(',\n'),
    ') as v (slug, position, qty, unit, item, group_name, ingredient_name)',
    'join public.recipes r on r.slug = v.slug',
    'join public.ingredients i on i.name = v.ingredient_name and i.owner_id = r.owner_id;',
    '',
    'insert into public.recipe_steps (recipe_id, position, title, text, timer_minutes)',
    'select r.id, v.position, v.title::text, v.text, v.timer_minutes::integer',
    'from (values',
    recipes
      .flatMap((r) =>
        r.steps.map(
          (s, index) =>
            `  (${text(r.slug)}, ${index + 1}, ${text(s.title)}, ${text(s.text)}, ${number(s.timerMinutes)})`,
        ),
      )
      .join(',\n'),
    ') as v (slug, position, title, text, timer_minutes)',
    'join public.recipes r on r.slug = v.slug;',
    '',
  );
  return sql.join('\n');
}

function generate() {
  const { names, staples } = JSON.parse(readFileSync(NAMES_FILE, 'utf8'));
  return buildSeedSql(loadRecipes(), { names, staples });
}

/** Asks the local stack for its URL and service key, without printing either. */
function localStack() {
  const result = spawnSync('supabase', ['status', '-o', 'json'], { encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(
      'Could not read `supabase status`. Is the local stack running (`supabase start`)?',
    );
  }
  const status = JSON.parse(result.stdout);
  const url = status.API_URL;
  const key = status.SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error('`supabase status` did not report an API URL and service key.');
  const host = new URL(url).hostname;
  if (host !== '127.0.0.1' && host !== 'localhost') {
    throw new Error(`Refusing to upload to a non-local URL (${host}).`);
  }
  return { url, key };
}

const CONTENT_TYPES = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
};

async function uploadImages() {
  const withImages = loadRecipes().filter((r) => r.image);
  if (!withImages.length) {
    console.log('No recipe has an `image`, so there are no photos to upload.');
    return;
  }
  const { url, key } = localStack();
  for (const r of withImages) {
    const file = `public${r.image}`;
    if (!existsSync(file)) throw new Error(`${r.slug}: ${file} does not exist.`);
    const objectPath = imageObjectPath(r);
    const response = await fetch(`${url}/storage/v1/object/${BUCKET}/${objectPath}`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${key}`,
        'Content-Type': CONTENT_TYPES[extname(file).toLowerCase()] ?? 'application/octet-stream',
        'x-upsert': 'true',
      },
      body: readFileSync(file),
    });
    if (!response.ok)
      throw new Error(`${r.slug}: upload failed (${response.status} ${await response.text()})`);
    console.log(`Uploaded ${objectPath}`);
  }
}

const mode = process.argv[2];
try {
  if (mode === '--images') {
    await uploadImages();
  } else if (mode === '--check') {
    const current = existsSync(SEED_FILE) ? readFileSync(SEED_FILE, 'utf8') : '';
    if (current !== generate()) {
      console.error(`${SEED_FILE} is out of date. Run \`npm run recipes:seed\`.`);
      process.exit(1);
    }
    console.log(`${SEED_FILE} is up to date.`);
  } else if (mode === undefined) {
    writeFileSync(SEED_FILE, generate());
    console.log(`Wrote ${SEED_FILE} for ${loadRecipes().length} recipes.`);
  } else {
    console.error(
      `Unknown option ${mode}. Use --check or --images, or no option to write the seed.`,
    );
    process.exit(2);
  }
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
